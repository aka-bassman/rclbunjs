// Builds the `declare module "rclbunjs"` augmentation for installed interfaces.
import type { MessageDefinition, MessageDefinitionField } from "@foxglove/message-definition";
import { listInterfacePackages, listInterfaces } from "./discovery.ts";
import { getActionType, getMessageType, getServiceType } from "./registry.ts";

const TYPED: Record<string, string> = {
  byte: "Uint8Array", octet: "Uint8Array", uint8: "Uint8Array", char: "Uint8Array",
  int8: "Int8Array", int16: "Int16Array", uint16: "Uint16Array", int32: "Int32Array",
  uint32: "Uint32Array", float32: "Float32Array", float64: "Float64Array",
};

const ident = (full: string) => full.replace(/\//g, "__");

function scalar(t: string): string {
  switch (t) {
    case "bool": return "boolean";
    case "int64": case "uint64": return "bigint";
    case "string": case "wstring": return "string";
  }
  return TYPED[t] !== undefined || ["int8", "int16", "int32", "uint16", "uint32", "float32", "float64"].includes(t) ? "number" : "unknown";
}

function fieldType(f: MessageDefinitionField): string {
  const base = f.isComplex ? ident(f.type) : scalar(f.type);
  if (!f.isArray) return base;
  if (!f.isComplex && TYPED[f.type]) return `${TYPED[f.type]} | number[]`;
  return `${base}[]`;
}

export function generateDeclarations(opts: { packages?: string[]; moduleName?: string } = {}) {
  const moduleName = opts.moduleName ?? "rclbunjs";
  const pkgs = opts.packages ?? listInterfacePackages();
  const structs = new Map<string, MessageDefinition>();
  const msgs: string[] = [];
  const srvs: string[] = [];
  const acts: string[] = [];
  const errors: string[] = [];
  const addDefs = (defs: MessageDefinition[]) => {
    for (const d of defs) if (d.name && !structs.has(d.name)) structs.set(d.name, d);
  };
  for (const pkg of pkgs) {
    for (const name of listInterfaces(pkg)) {
      try {
        const kind = name.split("/")[1];
        if (kind === "msg") {
          addDefs(getMessageType(name).definitions);
          msgs.push(name);
        } else if (kind === "srv") {
          const s = getServiceType(name);
          addDefs(s.request.definitions);
          addDefs(s.response.definitions);
          srvs.push(name);
        } else if (kind === "action") {
          const a = getActionType(name);
          for (const m of [a.goal, a.result, a.feedback]) addDefs(m.definitions);
          acts.push(name);
        }
      } catch (e) {
        errors.push(`${name}: ${(e as Error).message}`);
      }
    }
  }
  const lines: string[] = [
    "// Generated by rclbunjs-typegen. Do not edit.",
    `import "${moduleName}";`,
    "",
    `declare module "${moduleName}" {`,
  ];
  for (const [name, d] of [...structs].sort(([a], [b]) => a.localeCompare(b))) {
    const fields = d.definitions.filter((f) => !f.isConstant);
    const consts = d.definitions.filter((f) => f.isConstant);
    lines.push(`  /** ${name} */`);
    lines.push(`  interface ${ident(name)} {`);
    for (const f of fields) lines.push(`    ${f.name}: ${fieldType(f)};`);
    lines.push("  }");
    if (consts.length) {
      lines.push(`  /** constants of ${name} */`);
      lines.push(`  interface ${ident(name)}__Constants {`);
      for (const c of consts) lines.push(`    readonly ${c.name}: ${JSON.stringify(typeof c.value === "bigint" ? Number(c.value) : c.value)};`);
      lines.push("  }");
    }
  }
  lines.push("  interface MessageTypeMap {");
  for (const m of msgs.sort()) lines.push(`    "${m}": ${ident(m)};`);
  lines.push("  }");
  lines.push("  interface ServiceTypeMap {");
  for (const s of srvs.sort()) lines.push(`    "${s}": { Request: ${ident(s)}_Request; Response: ${ident(s)}_Response };`);
  lines.push("  }");
  lines.push("  interface ActionTypeMap {");
  for (const a of acts.sort()) lines.push(`    "${a}": { Goal: ${ident(a)}_Goal; Result: ${ident(a)}_Result; Feedback: ${ident(a)}_Feedback };`);
  lines.push("  }");
  lines.push("}", "");
  return { text: lines.join("\n"), counts: { messages: msgs.length, services: srvs.length, actions: acts.length }, errors };
}
